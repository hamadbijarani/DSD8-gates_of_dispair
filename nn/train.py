def split(x, y, seed):
    rng = np.random.default_rng(seed)
    idx = rng.permutation(len(y))
    n_tr = int(0.7 * len(y))
    n_va = int(0.15 * len(y))
    tr, va, te = idx[:n_tr], idx[n_tr:n_tr + n_va], idx[n_tr + n_va:]
    return (x[tr], y[tr]), (x[va], y[va]), (x[te], y[te])


def onehot(y, k=3):
    o = np.zeros((len(y), k))
    o[np.arange(len(y)), y] = 1.0
    return o


def train(epochs=800, lr=0.08, seed=SEED):
    rng = np.random.default_rng(seed)
    x, y = load_iris()
    xmin, xmax = x.min(0), x.max(0)
    x = (x - xmin) / (xmax - xmin)
    (xtr, ytr), (xva, yva), (xte, yte) = split(x, y, seed)
    ytr_o, yva_o, yte_o = onehot(ytr), onehot(yva), onehot(yte)

    w1 = rng.normal(0, 0.5, (4, 6))
    b1 = np.zeros(6)
    w2 = rng.normal(0, 0.5, (6, 3))
    b2 = np.zeros(3)

    def fwd(xb):
        h = np.maximum(xb @ w1 + b1, 0)
        z = h @ w2 + b2
        z = z - z.max(1, keepdims=True)
        e = np.exp(z)
        return h, e / e.sum(1, keepdims=True)

    best = None
    for ep in range(epochs):
        h, p = fwd(xtr)
        g = (p - ytr_o) / len(xtr)
        gw2 = h.T @ g
        gb2 = g.sum(0)
        gh = (g @ w2.T) * (h > 0)
        gw1 = xtr.T @ gh
        gb1 = gh.sum(0)
        w1 -= lr * gw1
        b1 -= lr * gb1
        w2 -= lr * gw2
        b2 -= lr * gb2
        if ep % 20 == 0:
            _, pv = fwd(xva)
            acc = (pv.argmax(1) == yva).mean()
            if best is None or acc >= best[0]:
                best = (acc, w1.copy(), b1.copy(), w2.copy(), b2.copy())

    _, w1, b1, w2, b2 = best
    _, pv = fwd(xva)
    _, pt = fwd(xte)
    print(f"val acc { (pv.argmax(1)==yva).mean():.4f}  test acc {(pt.argmax(1)==yte).mean():.4f}")
    return dict(w1=w1, b1=b1, w2=w2, b2=b2,
                x_min=xmin, x_max=xmax,
                xte=xte, yte=yte)


def main():
    DATA.mkdir(parents=True, exist_ok=True)
    best = None
    for r in range(6):
        m = train(seed=SEED + r)
        _, pv = (lambda xb: (None, (lambda h: h)(None)))(None)
        # recompute val accuracy from stored test split
        x, y = load_iris()
        xmin, xmax = x.min(0), x.max(0)
        x = (x - xmin) / (xmax - xmin)
        _, (xva, yva), _ = split(x, y, SEED + r)
        h = np.maximum(xva @ m["w1"] + m["b1"], 0)
        z = h @ m["w2"] + m["b2"]
        acc = (z.argmax(1) == yva).mean()
        print(f"restart {r}: val {acc:.4f}")
        if best is None or acc > best[0]:
            best = (acc, m)
    m = best[1]
    np.savez(DATA / "model_float.npz", **m)
    print(f"wrote {DATA/'model_float.npz'}")


if __name__ == "__main__":
    main()
