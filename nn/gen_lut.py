#!/usr/bin/env python3
"""Generate rtl/nn_lut_rom.v and nn/data/lut_*.json (deterministic)."""
import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_V = ROOT / "rtl" / "nn_lut_rom.v"
DATA = ROOT / "nn" / "data"


def s8(i):
    return i - 256 if i >= 128 else i


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def bank0(i):
    return i if i < 128 else 0


def bank1(i):
    x = s8(i)
    return clamp(int(round(255.0 / (1.0 + math.exp(-x / 16.0)))), 0, 255)


def bank2(i):
    return i ^ 0x80


def bank3(i):
    x = s8(i)
    return clamp(int(round(127.0 * math.tanh(x / 16.0))), -128, 127) & 0xFF


BANKS = [bank0, bank1, bank2, bank3]
NAMES = ["relu", "sigmoid", "offset_binary", "tanh"]


def main():
    DATA.mkdir(parents=True, exist_ok=True)
    for name, fn in zip(NAMES, BANKS):
        vals = [fn(i) for i in range(256)]
        (DATA / f"lut_{name}.json").write_text(json.dumps(vals) + "\n")
        (DATA / f"lut_{name}.hex").write_text(
            "".join(f"{v:02X}\n" for v in vals)
        )

    lines = [
        "// nn_lut_rom.v -- generated by nn/gen_lut.py; do not edit",
        "module nn_lut_rom (",
        "    input  wire [1:0] bank,",
        "    input  wire [7:0] idx,",
        "    output reg  [7:0] val",
        ");",
        "    always @(*) begin",
        "        case ({bank, idx})",
    ]
    for b, fn in enumerate(BANKS):
        for i in range(256):
            lines.append(f"            10'h{b:01x}{i:02x}: val = 8'h{fn(i):02x};")
    lines += [
        "            default: val = 8'h00;",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    OUT_V.write_text("\n".join(lines))
    print(f"wrote {OUT_V} and {len(BANKS)} JSON banks")


if __name__ == "__main__":
    main()
